async function buildStyles(registryItems: RegistryItem[]) {
  for (const style of styles) {
    const targetPath = path.join(REGISTRY_PATH, 'styles', style.name)

    // Create directory if it doesn't exist.
    if (!existsSync(targetPath)) {
      await fs.mkdir(targetPath, { recursive: true })
    }

    for (const item of registryItems) {
      if (!REGISTRY_INDEX_WHITELIST.includes(item.type)) {
        continue
      }

      let metadata: RegistryEntry = {} as any
      let files
      if (item.files) {
        // get metadata.json index and exclude from `files`
        const metadataIndex = item.files.findIndex(_file => _file.path.includes(METADATA_NAME))
        if (metadataIndex !== -1) {
          metadata = JSON.parse(item.files[metadataIndex].content ?? '{}')
        }

        files = await Promise.all(
          item.files.filter((_, index) => index !== metadataIndex).map(async (_file) => {
            const file = {
              path: _file.path,
              type: _file.type,
              content: '',
              target: _file.target ?? '',
            }

            let content: string
            try {
              content = await fs.readFile(
                path.join(process.cwd(), 'src', 'registry', style.name, file.path),
                'utf8',
              )
            }
            catch (error) {
              return
            }

            // TODO: remove meta content
            // const tempFile = await createTempSourceFile(file.path)
            // const sourceFile = project.createSourceFile(tempFile, content, {
            //   scriptKind: ScriptKind.TS,
            // })

            // sourceFile.getVariableDeclaration('iframeHeight')?.remove()
            // sourceFile.getVariableDeclaration('containerClassName')?.remove()
            // sourceFile.getVariableDeclaration('description')?.remove()

            const target = file.target || ''

            // if ((!target || target === '') && item.name.startsWith('v0-')) {
            //   const fileName = file.path.split('/').pop()
            //   if (
            //     file.type === 'registry:block'
            //     || file.type === 'registry:component'
            //     || file.type === 'registry:example'
            //   ) {
            //     target = `components/${fileName}`
            //   }

            //   if (file.type === 'registry:ui') {
            //     target = `components/ui/${fileName}`
            //   }

            //   if (file.type === 'registry:hook') {
            //     target = `hooks/${fileName}`
            //   }

            //   if (file.type === 'registry:lib') {
            //     target = `lib/${fileName}`
            //   }
            // }

            return {
              path: file.path,
              type: file.type,
              // content: sourceFile.getText(),
              content: eol.lf(content),
              target,
            }
          }),
        )
      }

      const payload = registryItemSchema
        .omit({
          // source: true,
          // chunks: true,
        })
        .safeParse({
          ...metadata,
          ...item,
          files,
        })

      if (payload.success) {
        await writeFile(
          path.join(targetPath, `${item.name}.json`),
          JSON.stringify(payload.data, null, 2),
        )
      }
    }
  }

  // ----------------------------------------------------------------------------
  // Build registry/styles/index.json.
  // ----------------------------------------------------------------------------
  const stylesJson = JSON.stringify(styles, null, 2)
  await writeFile(
    path.join(REGISTRY_PATH, 'styles/index.json'),
    stylesJson,

  )
}

