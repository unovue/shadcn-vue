// ----------------------------------------------------------------------------
// Build __registry__/block.ts.
// ----------------------------------------------------------------------------
async function buildBlockRegistry(registryItems: RegistryItem[]) {
  let index = `/* eslint-disable ts/ban-ts-comment */
// @ts-nocheck
// This file is autogenerated by scripts/build-registry.ts
// Do not edit this file directly.

export const Index: Record<string, any> = {
`

  for (const style of styles) {
    const itemSet = new Set<string>()
    index += `  "${style.name}": {`

    // Build style index.
    for (const item of registryItems) {
      if (item.type !== 'registry:block')
        continue

      if (itemSet.has(item.name))
        continue
      itemSet.add(item.name)

      const resolveFiles = item.files?.map(
        file =>
          `registry/${style.name}/${
            typeof file === 'string' ? file : file.path
          }`,
      )
      if (!resolveFiles) {
        continue
      }

      const type = item.type.split(':')[1]

      let componentPath = `@/registry/${style.name}/${type}/${item.name}`

      if (item.files) {
        const files = item.files.map(file =>
          typeof file === 'string'
            ? { type: 'registry:page', path: file }
            : file,
        )
        if (files?.length) {
          componentPath = `@/registry/${style.name}/${files[0].path}`
        }
      }

      index += `
    "${item.name}": {
      name: "${item.name}",
      description: "${item.description ?? ''}",
      type: "${item.type}",
      registryDependencies: ${JSON.stringify(item.registryDependencies)},
      files: [${item.files?.map((file) => {
        const filePath = `registry/${style.name}/${
          typeof file === 'string' ? file : file.path
        }`
        const resolvedFilePath = path.resolve(filePath)
        return typeof file === 'string'
          ? `"${resolvedFilePath}"`
          : `{
        path: "${filePath}",
        type: "${file.type}",
        target: "${file.target ?? ''}",
        raw: () => import("@/${filePath}?raw").then((m) => m.default)
      }`
      })}],
      component: () => import("${componentPath}").then((m) => m.default),
      raw: () => import("${componentPath}?raw").then((m) => m.default),
      source: "",
      categories: ${JSON.stringify(item.categories ?? [])}
    },`
    }

    index += `
  },`
  }

  index += `
}
`

  // Write style block.
  rimraf.sync(path.join(process.cwd(), '__registry__/block.ts'))
  await writeFile(path.join(process.cwd(), '__registry__/block.ts'), index)
}

